#!/usr/bin/env python3
"""Generate tables.h for the band-level score: synthetic 2 kHz audio table, Q28 band-pass SOS, log2 LUT, bin thresholds, float reference (needs NumPy and SciPy)."""
import numpy as np, scipy.signal as sg, math, os
FS = 2000; NTAB = 8192; UNIT_N = 20000; QC = 28
rng = np.random.RandomState(20261005)
t = np.arange(NTAB) / FS
# ocean-like ambient noise (sum of 4 uniforms ~ gaussian, rms ~ 350) + in-band tonal call 120-180 Hz (amp 600, intermittent) + out-of-band rumble 8 Hz (amp 4000) + 700 Hz tone
noise = sum(rng.uniform(-1, 1, NTAB) for _ in range(4)) * 350 / math.sqrt(4 / 3)
call = 600 * np.sin(2 * np.pi * (120 * t + 30 * t * t / t[-1] / 2)) * (np.sin(np.pi * t / t[-1]) ** 2)
rumble = 4000 * np.sin(2 * np.pi * 8 * t)
hi = 300 * np.sin(2 * np.pi * 700 * t)   # above Nyquist 1000? no: 700 Hz is above the 500 Hz band edge, below Nyquist
tab = np.clip(np.round(noise + call + rumble + hi), -15000, 15000).astype(np.int32)
sos = sg.butter(2, [25, 500], btype='band', fs=FS, output='sos')   # 2 biquads, 4th-order band-pass 25-500 Hz
coef = []
for s in sos:
    b0, b1, b2, a0, a1, a2 = s
    coef.append([int(round(v * (1 << QC))) for v in (b0, b1, b2, -a1, -a2)])   # a pre-negated: y = b0x+b1x1+b2x2 + c3*y1 + c4*y2
assert all(abs(v) < 2 ** 31 for c in coef for v in c)
lutlog = [int(round(256 * math.log2(1 + m / 64))) for m in range(64)]
THR = [(i - 6) * 64 for i in range(19)]   # Q8 log2 units above the causal baseline: 0.25 log2 (~0.75 dB energy) per bin step, 20 bins
# float reference of per-unit L (Q8 log2 energy), test schedule of gain shifts, filter state carried across units
SH = [3, 3, 0, 2, 3, 1, 3, 0]
def ref():
    zi = np.zeros((2, 2)); out = []; start = 0
    for sh in SH:
        idx = (start + np.arange(UNIT_N)) & (NTAB - 1)
        x = (tab[idx] >> sh).astype(float)
        y, zi = sg.sosfilt(sos, x, zi=zi)
        E = float(np.sum(y * y)); out.append(int(round(256 * math.log2(E))))
        start = (start + UNIT_N) & (NTAB - 1)
    return out
R = ref()
print('coef', coef); print('ref L_q8', R, 'max|tab|', abs(tab).max())
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables.h"), 'w') as f:
    f.write('/* generated by gen_tables.py -- do not edit */\n#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n')
    f.write('#define SC_FS %d\n#define SC_UNIT_N %d\n#define SC_NTAB %d\n#define SC_QC %d\n#define SC_NBIN 20\n#define SC_NTEST %d\n#ifndef SK_P\n#define SK_P 4\n#endif\n#define SK_UPP 2160\n' % (FS, UNIT_N, NTAB, QC, len(SH)))
    f.write('static const int32_t sc_coef[2][5] = {%s};\n' % ','.join('{%s}' % ','.join(map(str, c)) for c in coef))
    f.write('static const uint8_t sc_loglut[64] = {%s};\n' % ','.join(map(str, lutlog)))
    f.write('static const int16_t sc_thr[19] = {%s};\n' % ','.join(map(str, THR)))
    f.write('static const uint8_t sc_test_sh[SC_NTEST] = {%s};\n' % ','.join(map(str, SH)))
    f.write('static const int32_t sc_test_ref[SC_NTEST] = {%s};\n' % ','.join(map(str, R)))
    f.write('static const int16_t sc_audio[SC_NTAB] = {\n' + ',\n'.join(','.join(map(str, tab[i:i + 16])) for i in range(0, NTAB, 16)) + '};\n#endif\n')
